#!/bin/sh
# Compile the fixed shaders and every translated game shader with uam, and embed them as a C header.
# usage: build_shaders.sh <out.h>
set -eu
OUT=$1
U=/opt/devkitpro/tools/bin/uam
[ -x /b/tools/uam ] && U=/b/tools/uam  # patched build (tools/docker/build_uam.sh) when present
T=/tmp/sims3_shaders
rm -rf "$T"
mkdir -p "$T/glsl" "$T/dksh"
"$U" -s vert -o "$T/ui_vert.dksh" /nx/app/shaders/ui.vert.glsl
"$U" -s frag -o "$T/ui_frag.dksh" /nx/app/shaders/ui.frag.glsl
"$U" -s vert -o "$T/blit_vert.dksh" /nx/app/shaders/blit.vert.glsl
"$U" -s frag -o "$T/blit_frag.dksh" /nx/app/shaders/blit.frag.glsl
"$U" -s frag -o "$T/blit_depth_frag.dksh" /nx/app/shaders/blit_depth.frag.glsl
"$U" -s frag -o "$T/blit_stencil_frag.dksh" /nx/app/shaders/blit_stencil.frag.glsl
"$U" -s frag -o "$T/stencil_bit_frag.dksh" /nx/app/shaders/stencil_bit.frag.glsl
python3 -I /nx/tools/xenos2glsl.py /nx/work/ucode "$T/glsl"
# Debug only (work/debug_atlas.on): the Sim body shader outputs its texture colour unlit (green portraits).
if [ -f /nx/work/debug_atlas.on ]; then
  sed -i 's/^  oC0.xyz = pv.xyz;$/  oC0.xyz = r5.xyz;/' "$T/glsl/ps_2c16e2f2bf5b4fc7.glsl"
  grep -n "oC0.xyz = r5" "$T/glsl/ps_2c16e2f2bf5b4fc7.glsl"
fi
sh /nx/tools/docker/compile_shaders.sh "$T/glsl" "$T/dksh"
python3 - "$T" "$OUT" <<'EOF'
import glob, json, os, re, sys
def constant_mask(path):
    # 256-bit mask of the float constants a shader reads; relative addressing can read any of them.
    text = "\n".join(l for l in open(path).read().splitlines() if "uniform Floats" not in l)
    if "c[(a0" in text:
        return [0xFFFFFFFFFFFFFFFF] * 4
    mask = [0] * 4
    for i in set(int(x) for x in re.findall(r"\bc\[(\d+)\]", text)):
        mask[i >> 6] |= 1 << (i & 63)
    return mask
tmp, out = sys.argv[1], sys.argv[2]
manifest = json.load(open(tmp + "/glsl/manifest.json"))
with open(out, "w") as f:
    f.write("#pragma once\n#include <cstdint>\n// Generated by tools/docker/build_shaders.sh\n")
    for name in ("ui_vert", "ui_frag", "blit_vert", "blit_frag", "blit_depth_frag", "blit_stencil_frag", "stencil_bit_frag"):
        data = open("%s/%s.dksh" % (tmp, name), "rb").read()
        f.write("alignas(256) inline const uint8_t k_%s[%d] = {%s};\n" % (name, len(data), ",".join(map(str, data))))
    rows = []
    for path in sorted(glob.glob(tmp + "/dksh/*.dksh")):
        name = os.path.basename(path)[:-5]
        data = open(path, "rb").read()
        f.write("inline const uint8_t k_x_%s[%d] = {%s};\n" % (name, len(data), ",".join(map(str, data))))
        m = manifest[name]
        fetch = m["fetch"][:8]
        two = sum(1 << int(k) for k, v in m["textures"].items() if v == "2d")
        cube = sum(1 << int(k) for k, v in m["textures"].items() if v == "cube")
        mask = constant_mask("%s/glsl/%s.glsl" % (tmp, name))
        rows.append("  {0x%sull, k_x_%s, %d, %d, {%s}, 0x%Xu, 0x%Xu, {%s}},\n" % (
            name[3:], name, len(data), len(fetch), ",".join(map(str, fetch + [0] * (8 - len(fetch)))), two, cube,
            ",".join("0x%Xull" % v for v in mask)))
    f.write("struct XenosShader {\n  uint64_t hash;\n  const uint8_t* code;\n  uint32_t size, fetch_count;\n"
            "  uint8_t fetch[8];\n  uint32_t textures_2d, textures_cube;\n  uint64_t constants[4];\n};\n")
    f.write("inline const XenosShader k_xenos_shaders[] = {\n%s};\n" % "".join(rows))
print("embedded", len(rows), "game shaders")
EOF
ls -l "$OUT"
